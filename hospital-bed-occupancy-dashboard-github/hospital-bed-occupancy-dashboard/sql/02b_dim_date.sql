-- Populate calendar for the analysis window
INSERT INTO dim_date
SELECT d,
       EXTRACT(YEAR FROM d), EXTRACT(MONTH FROM d), TRUNC(d,'MM'),
       TO_CHAR(d,'Mon','NLS_DATE_LANGUAGE=ENGLISH'),
       TO_CHAR(d,'DY','NLS_DATE_LANGUAGE=ENGLISH'),
       CASE WHEN TO_CHAR(d,'DY','NLS_DATE_LANGUAGE=ENGLISH') IN ('SAT','SUN') THEN 'Y' ELSE 'N' END
FROM (SELECT DATE '2024-01-01' + LEVEL - 1 AS d FROM dual
      CONNECT BY LEVEL <= DATE '2025-06-30' - DATE '2024-01-01' + 1);
COMMIT;
